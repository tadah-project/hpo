/* hpo_registry_export -- writes the optimiser registry of `tadah hpo` as
 * TOML, blueprint/optimizers_gen.toml, written for the documentation: it
 * is built without C++, so it cannot ask the registry itself.
 *
 *   hpo_registry_export                 the TOML text on standard output
 *   hpo_registry_export --write FILE    the TOML text into FILE
 *   hpo_registry_export --check FILE    exit status 0 when FILE holds
 *                                       exactly that text, 1 otherwise
 *
 * The entries are sorted by LIB, then ALGO. The text is the same in every
 * build of one NLopt version (the version is part of it): the ALGO help is
 * written without the lines that say what a build lacks
 * (BuildNotes::Omit, optimizer_spec.h). Before the text is written or
 * compared, it is read back as TOML (toml11), and every value must be the
 * one written. Exit status 2: a usage error. blueprint/README.md says what
 * the file is generated from, how it is regenerated and how it is checked.
 */

