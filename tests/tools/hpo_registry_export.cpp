/* hpo_registry_export -- writes the optimiser registry of `tadah hpo` as
 * TOML, blueprint/optimizers_gen.toml, which the documentation reads: it is
 * built without C++, so it cannot ask the registry itself.
 *
 *   hpo_registry_export                 the TOML text on standard output
 *   hpo_registry_export --write FILE    the TOML text into FILE
 *   hpo_registry_export --check FILE    exit status 0 when FILE holds
 *                                       exactly that text, 1 otherwise
 *
 * The text is sorted and the same in every build of one NLopt version
 * (the version is part of it). CTest hpo_optimizer_registry_sync runs
 * --check on the checked-in file; the target
 * hpo_regenerate_optimizer_registry runs --write on it. Before the text is
 * written or compared, it is read back as TOML (toml11), and every value
 * must be the one written. Exit status 2: a usage error.
 */

#include <toml.hpp>

#include <nlopt.hpp>

#include <cstddef>
#include <cstdint>
#include <fstream>
#include <iostream>
#include <sstream>
#include <stdexcept>
#include <string>
#include <utility>
#include <variant>
#include <vector>

namespace {

/* ---- the document --------------------------------------------------- */

using Strings = std::vector<std::string>;
using Value = std::variant<bool, std::int64_t, std::string, Strings>;

struct Field {
    std::string key;
    Value value;
    bool multiline = false;  // a string written as a multi-line string
};

struct Table {
    std::vector<Field> fields;

    void add(std::string key, Value value, bool multiline = false)
    {
        fields.push_back({std::move(key), std::move(value), multiline});
    }
};

struct Document {
    Table meta;
};

constexpr const char* kHeader =
    "# The optimisers of tadah hpo: every LIB:ALGO an OPTIMIZER block can\n"
    "# name, registered or refused, with its capabilities and its ALGO help.\n"
    "#\n"
    "# Generated by hpo_registry_export (tests/tools/hpo_registry_export.cpp)\n"
    "# from the optimiser registry (src/optimizer_caps.cpp) and the ALGO help\n"
    "# (src/optimizer_spec.cpp). Do not edit this file: regenerate it from a\n"
    "# build directory B with\n"
    "#   cmake --build B --target hpo_regenerate_optimizer_registry\n"
    "# CTest hpo_optimizer_registry_sync fails when it differs from what the\n"
    "# code produces. The fields: blueprint/README.md.\n";

std::string nlopt_version()
{
    int major = 0, minor = 0, bugfix = 0;
    nlopt::version(major, minor, bugfix);
    return std::to_string(major) + "." + std::to_string(minor) + "." +
           std::to_string(bugfix);
}

Document build_document()
{
    Document doc;
    doc.meta.add("schema", std::int64_t{1});
    doc.meta.add("nlopt_version", nlopt_version());
    return doc;
}

/* ---- TOML text ------------------------------------------------------- */

/* The characters of `s` as a TOML basic string needs them: a backslash
 * and a double quote escaped, and every control character; in a
 * multi-line string a line feed stays one. */
std::string escape(const std::string& s, bool multiline)
{
    static const char* const hex = "0123456789ABCDEF";
    std::string out;
    for (const char ch : s) {
        const auto u = static_cast<unsigned char>(ch);
        switch (ch) {
            case '\\': out += "\\\\"; continue;
            case '"':  out += "\\\""; continue;
            case '\b': out += "\\b";  continue;
            case '\t': out += "\\t";  continue;
            case '\f': out += "\\f";  continue;
            case '\r': out += "\\r";  continue;
            case '\n': out += multiline ? "\n" : "\\n"; continue;
            default: break;
        }
        if (u < 0x20 || u == 0x7F) {
            out += "\\u00";
            out += hex[u >> 4];
            out += hex[u & 0xF];
        } else {
            out += ch;
        }
    }
    return out;
}

void write_value(std::ostream& os, const Field& f)
{
    if (const bool* b = std::get_if<bool>(&f.value)) {
        os << (*b ? "true" : "false");
    } else if (const std::int64_t* i = std::get_if<std::int64_t>(&f.value)) {
        os << *i;
    } else if (const std::string* s = std::get_if<std::string>(&f.value)) {
        if (f.multiline)
            os << "\"\"\"\n" << escape(*s, true) << "\"\"\"";
        else
            os << '"' << escape(*s, false) << '"';
    } else {
        const Strings& list = std::get<Strings>(f.value);
        os << '[';
        for (std::size_t i = 0; i < list.size(); ++i)
            os << (i ? ", " : "") << '"' << escape(list[i], false) << '"';
        os << ']';
    }
}

void write_table(std::ostream& os, const Table& t)
{
    for (const Field& f : t.fields) {
        os << f.key << " = ";
        write_value(os, f);
        os << "\n";
    }
}

std::string write_document(const Document& doc)
{
    std::ostringstream os;
    os << kHeader << "\n[meta]\n";
    write_table(os, doc.meta);
    return os.str();
}

/* ---- read-back check ------------------------------------------------- */

/* Throws std::runtime_error unless the TOML table `got` has exactly the
 * keys of `want`, each with the value written. */
void check_table(const toml::value& got, const Table& want,
                 const std::string& where)
{
    if (!got.is_table())
        throw std::runtime_error(where + " is not a table");
    if (got.as_table().size() != want.fields.size())
        throw std::runtime_error(where + " has " +
                                 std::to_string(got.as_table().size()) +
                                 " keys, " +
                                 std::to_string(want.fields.size()) +
                                 " written");
    for (const Field& f : want.fields) {
        const std::string at = where + "." + f.key;
        if (!got.contains(f.key))
            throw std::runtime_error(at + " is missing");
        const toml::value& v = got.at(f.key);
        bool same = false;
        if (const bool* b = std::get_if<bool>(&f.value)) {
            same = v.is_boolean() && v.as_boolean() == *b;
        } else if (const std::int64_t* i = std::get_if<std::int64_t>(&f.value)) {
            same = v.is_integer() && v.as_integer() == *i;
        } else if (const std::string* s = std::get_if<std::string>(&f.value)) {
            same = v.is_string() && v.as_string().str == *s;
        } else {
            const Strings& list = std::get<Strings>(f.value);
            same = v.is_array() && v.as_array().size() == list.size();
            for (std::size_t i = 0; same && i < list.size(); ++i)
                same = v.as_array()[i].is_string() &&
                       v.as_array()[i].as_string().str == list[i];
        }
        if (!same)
            throw std::runtime_error(at + " does not read back as written");
    }
}

/* Throws std::runtime_error unless `text` is TOML that holds `doc`. */
void check_read_back(const Document& doc, const std::string& text)
{
    toml::value root;
    try {
        std::istringstream in(text);
        root = toml::parse(in, "the export");
    } catch (const std::exception& e) {
        throw std::runtime_error(std::string("the text is not TOML: ") +
                                 e.what());
    }
    if (root.as_table().size() != 1)
        throw std::runtime_error("the text has " +
                                 std::to_string(root.as_table().size()) +
                                 " top-level keys, 1 written");
    check_table(root.at("meta"), doc.meta, "meta");
}

/* ---- the command ----------------------------------------------------- */

/* The line `n` (from 1) of `s`, without its line feed; "(end of file)"
 * past the last one. */
std::string line_of(const std::string& s, std::size_t n)
{
    std::istringstream in(s);
    std::string line;
    for (std::size_t i = 0; i < n; ++i)
        if (!std::getline(in, line)) return "(end of file)";
    return line;
}

/* The number (from 1) of the first line where `a` and `b` differ. */
std::size_t first_difference(const std::string& a, const std::string& b)
{
    std::size_t line = 1;
    for (std::size_t i = 0; i < a.size() && i < b.size(); ++i) {
        if (a[i] != b[i]) return line;
        if (a[i] == '\n') ++line;
    }
    return line;
}

std::string regenerate_hint(const std::string& self, const std::string& file)
{
    return "Regenerate it from the build directory B with\n"
           "  cmake --build B --target hpo_regenerate_optimizer_registry\n"
           "or\n"
           "  " + self + " --write " + file + "\n";
}

int usage(const std::string& self)
{
    std::cerr << "usage: " << self << " [--write FILE | --check FILE]\n";
    return 2;
}

}  // namespace

int main(int argc, char** argv)
{
    const std::string self = argc > 0 ? argv[0] : "hpo_registry_export";
    std::string mode, file;
    if (argc == 3) {
        mode = argv[1];
        file = argv[2];
        if (mode != "--write" && mode != "--check") return usage(self);
    } else if (argc != 1) {
        return usage(self);
    }

    std::string text;
    try {
        const Document doc = build_document();
        text = write_document(doc);
        check_read_back(doc, text);
    } catch (const std::exception& e) {
        std::cerr << self << ": the export is wrong: " << e.what() << "\n";
        return 1;
    }

    if (mode.empty()) {
        std::cout << text;
        return std::cout ? 0 : 1;
    }
    if (mode == "--write") {
        std::ofstream out(file, std::ios::binary | std::ios::trunc);
        out << text;
        out.close();
        if (!out) {
            std::cerr << self << ": cannot write " << file << "\n";
            return 1;
        }
        std::cout << "wrote " << file << "\n";
        return 0;
    }

    std::ifstream in(file, std::ios::binary);
    if (!in) {
        std::cerr << file << " does not exist or cannot be read: it is the "
                     "optimiser registry the documentation reads.\n"
                  << regenerate_hint(self, file);
        return 1;
    }
    std::ostringstream held;
    held << in.rdbuf();
    if (held.str() == text) {
        std::cout << file << " matches the optimiser registry\n";
        return 0;
    }
    const std::size_t n = first_difference(held.str(), text);
    std::cerr << file << " differs from the optimiser registry, first at "
                 "line " << n << ":\n"
              << "  file:     " << line_of(held.str(), n) << "\n"
              << "  registry: " << line_of(text, n) << "\n"
              << regenerate_hint(self, file);
    return 1;
}
